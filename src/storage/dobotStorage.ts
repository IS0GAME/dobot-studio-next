import { MotionStyle, ToolAction, Waypoint } from '../types/robot';

export interface DobotProject {
  version: string;
  name: string;
  created: string;
  settings: {
    motionType: MotionStyle;
    speedRatio: number;
    acceleration: number;
    loopCount: number;
  };
  waypoints: Waypoint[];
}

export class DobotStorage {
  static exportToJson(project: DobotProject): string {
    return JSON.stringify(project, null, 2);
  }

  static importFromJson(jsonStr: string): DobotProject {
    return JSON.parse(jsonStr) as DobotProject;
  }

  static exportToLegacyPlaybackXml(waypoints: Waypoint[]): string {
    let xml = '<root><row_StudioVersion><item_0>Ver-170</item_0></row_StudioVersion>';
    waypoints.forEach((wp, idx) => {
      let motionCode = '1'; // MOVJ
      if (wp.motionStyle === 'MOVL') motionCode = '2';
      else if (wp.motionStyle === 'JUMP') motionCode = '0';
      else if (wp.motionStyle === 'CP') motionCode = '3';
      else if (wp.motionStyle === 'ARC') motionCode = '4';

      let suctionCode = '0';
      let gripperCode = '0';
      if (wp.toolAction.type === 'suction_cup') {
        suctionCode = wp.toolAction.enabled ? '1' : '0';
      } else if (wp.toolAction.type === 'gripper') {
        gripperCode = wp.toolAction.state === 'close' ? '1' : '0';
      }

      xml += `<row${idx}>`;
      xml += `<item_0>${motionCode}</item_0>`;
      xml += `<item_1>${wp.name || `P${idx + 1}`}</item_1>`;
      xml += `<item_2>${wp.coords.x.toFixed(1)}</item_2>`;
      xml += `<item_3>${wp.coords.y.toFixed(1)}</item_3>`;
      xml += `<item_4>${wp.coords.z.toFixed(1)}</item_4>`;
      xml += `<item_5>${wp.coords.r.toFixed(1)}</item_5>`;
      xml += `<item_10>${(wp.pauseTime || 0).toFixed(1)}</item_10>`;
      xml += `<item_12>${suctionCode}</item_12>`;
      xml += `<item_13>${gripperCode}</item_13>`;
      xml += `</row${idx}>`;
    });
    xml += '</root>';
    return xml;
  }

  static importFromLegacyPlaybackXml(xmlStr: string): Waypoint[] {
    const waypoints: Waypoint[] = [];
    const rowMatches = xmlStr.matchAll(/<row(\d+)>([\s\S]*?)<\/row\1>/g);

    for (const match of rowMatches) {
      const content = match[2];
      const getItem = (idx: number, fallback: string = '0'): string => {
        const itemMatch = content.match(new RegExp(`<item_${idx}>([^<]*)<\\/item_${idx}>`));
        return itemMatch ? itemMatch[1] : fallback;
      };

      const motionCode = getItem(0, '1');
      let motionStyle: MotionStyle = 'MOVJ';
      if (motionCode === '2') motionStyle = 'MOVL';
      else if (motionCode === '0') motionStyle = 'JUMP';
      else if (motionCode === '3') motionStyle = 'CP';
      else if (motionCode === '4') motionStyle = 'ARC';

      const name = getItem(1, `P${waypoints.length + 1}`);
      const x = parseFloat(getItem(2, '230.0')) || 230.0;
      const y = parseFloat(getItem(3, '0.0')) || 0.0;
      const z = parseFloat(getItem(4, '-10.0')) || -10.0;
      const r = parseFloat(getItem(5, '0.0')) || 0.0;
      const pauseTime = parseFloat(getItem(10, '0.0')) || 0.0;
      const suctionCode = getItem(12, '0');
      const gripperCode = getItem(13, '0');

      let toolAction: ToolAction = { type: 'none' };
      if (suctionCode === '1') {
        toolAction = { type: 'suction_cup', enabled: true };
      } else if (gripperCode === '1') {
        toolAction = { type: 'gripper', state: 'close' };
      }

      waypoints.push({
        id: `wp-${waypoints.length + 1}`,
        name,
        coords: { x, y, z, r },
        motionStyle,
        pauseTime,
        toolAction,
      });
    }
    return waypoints;
  }

  static exportToPython(waypoints: Waypoint[]): string {
    let py = '#!/usr/bin/env python\n# -*- coding: utf-8 -*-\n';
    py += '# Generated by Dobot Studio Next-Gen\n\n';
    py += 'import DobotDllType as dType\nimport time\n\n';
    py += 'api = dType.load()\n';
    py += 'state = dType.ConnectDobot(api, "", 115200)[0]\n';
    py += 'if state != dType.DobotConnect.DobotConnect_NoError:\n';
    py += '    print("Connect failed!")\n    exit(1)\n\n';
    py += 'dType.SetQueuedCmdClear(api)\n';
    py += 'dType.SetQueuedCmdStartExec(api)\n\n';

    waypoints.forEach((wp, idx) => {
      py += `# Step ${idx + 1}: ${wp.name}\n`;
      let ptpMode = 'dType.PTPMode.PTPMOVJXYZMode';
      if (wp.motionStyle === 'MOVL') ptpMode = 'dType.PTPMode.PTPMOVLXYZMode';
      else if (wp.motionStyle === 'JUMP') ptpMode = 'dType.PTPMode.PTPJUMPXYZMode';

      py += `dType.SetPTPCmd(api, ${ptpMode}, ${wp.coords.x.toFixed(2)}, ${wp.coords.y.toFixed(2)}, ${wp.coords.z.toFixed(2)}, ${wp.coords.r.toFixed(2)}, isQueued=1)\n`;

      if (wp.toolAction.type === 'suction_cup') {
        const val = wp.toolAction.enabled ? '1' : '0';
        py += `dType.SetEndEffectorSuctionCup(api, 1, ${val}, isQueued=1)\n`;
      } else if (wp.toolAction.type === 'gripper') {
        const val = wp.toolAction.state === 'close' ? '1' : '0';
        py += `dType.SetEndEffectorGripper(api, 1, ${val}, isQueued=1)\n`;
      }

      if (wp.pauseTime > 0) {
        py += `dType.SetWAITCmd(api, ${Math.round(wp.pauseTime * 1000)}, isQueued=1)\n`;
      }
      py += '\n';
    });

    py += 'print("Playback sequence sent to Dobot queue successfully.")\n';
    return py;
  }
}
